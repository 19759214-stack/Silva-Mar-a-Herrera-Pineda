# 1. Crea la variable galletas = 1
galletas = 1

# 2. Escribe una estructura while que se ejecute mientras galletas <= 4
while galletas <= 4:
    # 3. Dentro del bucle, imprime el mensaje usando f-string
    print(f"Tom se comió la galleta {galletas} 🍪")
    # 4. Suma 1 a la variable galletas para avanzar el contador
    galletas = galletas + 1