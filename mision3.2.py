# 1. Crea la variable minutos = 3
minutos = 3

# 2. Escribe una estructura while que se ejecute mientras minutos > 0
while minutos > 0:
    # 3. Dentro del bucle, imprime el mensaje usando f-string
    print(f"Faltan {minutos} minutos para que Tom despierte... ⏰")
    # 4. Resta 1 a la variable minutos
    minutos = minutos - 1

# 5. Fuera del bucle (sin sangría/espacios), agrega un print final
print("¡Tom ya despertó! 😸 🔔")